local ls = require("luasnip")
local s = ls.snippet
local t = ls.text_node
local i = ls.insert_node
local fmt = require("luasnip.extras.fmt").fmt

return {
	---------------------------------------------------------------------------
	-- BASIC MATH
	---------------------------------------------------------------------------

	s(
		"ff",
		fmt("\\frac{{{}}}{{{}}}", {
			i(1),
			i(2),
		})
	),

	s(
		"sq",
		fmt("\\sqrt{{{}}}", {
			i(1),
		})
	),

	s(
		"abs",
		fmt("\\left|{}\\right|", {
			i(1),
		})
	),

	s(
		"norm",
		fmt("\\left\\|{}\\right\\|", {
			i(1),
		})
	),

	s(
		"sr",
		fmt("{}^{{{}}}", {
			i(1, "x"),
			i(2),
		})
	),

	s(
		"sb",
		fmt("{}_{{{}}}", {
			i(1, "x"),
			i(2),
		})
	),

	---------------------------------------------------------------------------
	-- CALCULUS
	---------------------------------------------------------------------------

	s(
		"int",
		fmt("\\int_{{{}}}^{{{}}} {}\\,d{}", {
			i(1),
			i(2),
			i(3),
			i(4, "x"),
		})
	),

	s(
		"oint",
		fmt("\\oint {}\\,d{}", {
			i(1),
			i(2, "l"),
		})
	),

	s(
		"sum",
		fmt("\\sum_{{{}}}^{{{}}} {}", {
			i(1),
			i(2),
			i(3),
		})
	),

	s(
		"prod",
		fmt("\\prod_{{{}}}^{{{}}} {}", {
			i(1),
			i(2),
			i(3),
		})
	),

	s(
		"lim",
		fmt("\\lim_{{{}}} {}", {
			i(1, "x \\to 0"),
			i(2),
		})
	),

	s(
		"der",
		fmt("\\frac{{d {}}}{{d {}}}", {
			i(1, "f"),
			i(2, "x"),
		})
	),

	s(
		"pder",
		fmt("\\frac{{\\partial {}}}{{\\partial {}}}", {
			i(1, "f"),
			i(2, "x"),
		})
	),

	---------------------------------------------------------------------------
	-- VECTORS / LINEAR ALGEBRA
	---------------------------------------------------------------------------

	s(
		"vec",
		fmt("\\vec{{{}}}", {
			i(1),
		})
	),

	s(
		"unit",
		fmt("\\hat{{{}}}", {
			i(1),
		})
	),

	s(
		"dot",
		fmt("{} \\cdot {}", {
			i(1, "a"),
			i(2, "b"),
		})
	),

	s(
		"cross",
		fmt("{} \\times {}", {
			i(1, "a"),
			i(2, "b"),
		})
	),

	s(
		"bb",
		fmt("\\mathbb{{{}}}", {
			i(1, "R"),
		})
	),

	s(
		"cal",
		fmt("\\mathcal{{{}}}", {
			i(1, "F"),
		})
	),

	s(
		"bf",
		fmt("\\mathbf{{{}}}", {
			i(1),
		})
	),

	---------------------------------------------------------------------------
	-- PHYSICS / MECHANICS
	---------------------------------------------------------------------------

	s(
		"ev",
		fmt("\\langle {} \\rangle", {
			i(1, "A"),
		})
	),

	s(
		"comm",
		fmt("[{}, {}]", {
			i(1, "A"),
			i(2, "B"),
		})
	),

	s(
		"exp",
		fmt("e^{{{}}}", {
			i(1),
		})
	),

	s(
		"lag",
		fmt("\\mathcal{{L}} = {} - {}", {
			i(1, "T"),
			i(2, "V"),
		})
	),

	s(
		"ham",
		fmt("\\mathcal{{H}} = {}", {
			i(1),
		})
	),

	s(
		"fourier",
		fmt("\\tilde{{{}}}({}) = \\int_{{-\\infty}}^{{\\infty}} {} e^{{-i {} {}}}\\,d{}", {
			i(1, "f"),
			i(2, "k"),
			i(3, "f(x)"),
			i(4, "k"),
			i(5, "x"),
			i(6, "x"),
		})
	),

	---------------------------------------------------------------------------
	-- QUANTUM MECHANICS
	---------------------------------------------------------------------------

	s(
		"ket",
		fmt("\\ket{{{}}}", {
			i(1, "\\psi"),
		})
	),

	s(
		"bra",
		fmt("\\bra{{{}}}", {
			i(1, "\\psi"),
		})
	),

	s(
		"braket",
		fmt("\\bra{{{}}} {} \\ket{{{}}}", {
			i(1, "\\psi"),
			i(2, "A"),
			i(3, "\\psi"),
		})
	),

	s(
		"expect",
		fmt("\\langle {} | {} | {} \\rangle", {
			i(1, "\\psi"),
			i(2, "A"),
			i(3, "\\psi"),
		})
	),

	s(
		"commutator",
		fmt("[{}, {}]", {
			i(1, "\\hat{x}"),
			i(2, "\\hat{p}"),
		})
	),

	---------------------------------------------------------------------------
	-- EQUATIONS / ENVIRONMENTS
	---------------------------------------------------------------------------

	s(
		"eq",
		fmt(
			[[
\begin{{equation}}
    {}
\end{{equation}}
]],
			{
				i(1),
			}
		)
	),

	s(
		"ali",
		fmt(
			[[
\begin{{align}}
    {} &= {}
\end{{align}}
]],
			{
				i(1),
				i(2),
			}
		)
	),

	s(
		"cases",
		fmt(
			[[
\begin{{cases}}
    {} & {} \\
    {} & {}
\end{{cases}}
]],
			{
				i(1),
				i(2),
				i(3),
				i(4),
			}
		)
	),

	s(
		"mat",
		fmt(
			[[
\begin{{pmatrix}}
    {} & {} \\
    {} & {}
\end{{pmatrix}}
]],
			{
				i(1),
				i(2),
				i(3),
				i(4),
			}
		)
	),
}
